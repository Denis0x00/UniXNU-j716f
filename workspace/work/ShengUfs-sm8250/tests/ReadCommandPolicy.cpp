namespace p = shengufs::read_policy;
static unsigned checks = 0;

static void be32(uint8_t *out, uint32_t value)
{
  out[0] = uint8_t(value >> 24); out[1] = uint8_t(value >> 16);
  out[2] = uint8_t(value >> 8); out[3] = uint8_t(value);
}
static void le32(uint8_t *out, uint32_t value)
{
  out[0] = uint8_t(value); out[1] = uint8_t(value >> 8);
  out[2] = uint8_t(value >> 16); out[3] = uint8_t(value >> 24);
}
static p::Context context(uint64_t base = 0x90000000)
{
  p::Context c{};
  c.selected_lun = 3; c.expected_tag = 0x3d;
  c.dma = {{base, 139264}, {base, 32}, {base + 4096, 32},
           {base + 4608, 512}, {base + 5120, 16}, {base + 8192, 131072}};
  c.capacity = {true, c.selected_lun, 4096, 128};
  c.known_blocks[0] = {c.selected_lun, 7}; c.known_block_count = 1;
  return c;
}
static void prd(p::Request &r, uint64_t address, uint32_t bytes)
{
  le32(r.prd, uint32_t(address)); le32(r.prd + 4, uint32_t(address >> 32));
  le32(r.prd + 8, 0); le32(r.prd + 12, bytes - 1);
  r.prd_count = 1;
}
// Independent packet fixtures, never generated by the policy under test.
static p::Request request(p::Command command, const p::Context &c)
{
  p::Request r{};
  r.upiu[3] = c.expected_tag;
  switch (command) {
    case p::Command::Nop: break;
    case p::Command::PowerMode:
      r.upiu[0] = 0x16; r.upiu[5] = 1; r.upiu[12] = 3; r.upiu[13] = 2; break;
    case p::Command::TestUnitReady:
      r.upiu[0] = 1; r.upiu[2] = c.selected_lun; break;
    case p::Command::ReadCapacity10:
      r.upiu[0] = 1; r.upiu[1] = 0x40; r.upiu[2] = c.selected_lun;
      r.upiu[15] = 8; r.upiu[16] = 0x25;
      r.direction = p::Direction::FromDevice; r.data_bytes = 8;
      prd(r, c.dma.data.address, 8); break;
    case p::Command::Read10:
      r.upiu[0] = 1; r.upiu[1] = 0x40; r.upiu[2] = c.selected_lun;
      r.upiu[14] = 0x10; r.upiu[16] = 0x28; r.upiu[21] = 7; r.upiu[24] = 1;
      r.direction = p::Direction::FromDevice; r.data_bytes = 4096;
      prd(r, c.dma.data.address, 4096); break;
    default: assert(false);
  }
  return r;
}
static p::Accepted accept(const p::Request &r, const p::Context &c)
{
  p::Accepted a{};
  assert(p::validateRequest(r, c, a) == p::Error::None && a.valid);
  ++checks;
  return a;
}
static void reject(const p::Request &r, const p::Context &c)
{
  p::Accepted a{true, p::Command::Read10, 3, 0x3d, 4096, 7, c.dma.data.address};
  uint8_t original_r[sizeof(r)], original_c[sizeof(c)];
  std::memcpy(original_r, &r, sizeof(r)); std::memcpy(original_c, &c, sizeof(c));
  assert(p::validateRequest(r, c, a) != p::Error::None);
  assert(!a.valid && a.command == p::Command::None && !a.lun && !a.tag &&
         !a.data_bytes && !a.lba && !a.data_address);
  assert(std::memcmp(original_r, &r, sizeof(r)) == 0);
  assert(std::memcmp(original_c, &c, sizeof(c)) == 0);
  ++checks;
}
static const p::Command commands[] = {p::Command::Nop, p::Command::PowerMode,
  p::Command::TestUnitReady, p::Command::ReadCapacity10, p::Command::Read10};

static void testRequestPackets()
{
  const auto c = context();
  for (auto command : commands) {
    const auto good = request(command, c);
    const auto a = accept(good, c);
    assert(a.command == command && a.tag == c.expected_tag && a.data_bytes == good.data_bytes);
    // Every single-bit change to a complete canonical UPIU is rejected for
    // this exact tag, selected LUN, command and one-block allowlist.
    for (unsigned byte = 0; byte < 32; ++byte) {
      for (unsigned bit = 0; bit < 8; ++bit) {
        auto r = good; r.upiu[byte] ^= uint8_t(1U << bit); reject(r, c);
      }
    }
    for (unsigned d = 0; d < 256; ++d) {
      auto r = good; r.direction = static_cast<p::Direction>(d);
      if (r.direction != good.direction) reject(r, c);
    }
    for (uint32_t bytes : {0U, 1U, 4U, 8U, 4096U, 8192U, 131072U, 0xffffffffU}) {
      auto r = good; r.data_bytes = bytes;
      if (bytes != good.data_bytes) reject(r, c);
    }
    for (unsigned n : {0U, 1U, 2U, 32U, 0xffffffffU}) {
      auto r = good; r.prd_count = n;
      if (n != good.prd_count) reject(r, c);
    }
    for (unsigned tag = 0; tag < 256; ++tag) {
      auto r = good; r.upiu[3] = uint8_t(tag);
      if (tag != c.expected_tag) reject(r, c);
    }
    if (!good.data_bytes) {
      for (unsigned byte = 0; byte < 16; ++byte) {
        auto r = good; r.prd[byte] = 1; reject(r, c);
      }
    }
  }
  // Exhaust every transaction and every SCSI opcode, including side-effectful
  // no-data commands. The allowlist is by exact complete packet, not direction.
  for (unsigned op = 0; op < 256; ++op) {
    auto r = request(p::Command::TestUnitReady, c); r.upiu[16] = uint8_t(op);
    if (op != 0) reject(r, c);
    r = request(p::Command::Nop, c); r.upiu[0] = uint8_t(op);
    if (op != 0) reject(r, c);
    r = request(p::Command::PowerMode, c); r.upiu[12] = uint8_t(op);
    if (op != 3) reject(r, c);
    r = request(p::Command::PowerMode, c); r.upiu[13] = uint8_t(op);
    if (op != 2) reject(r, c);
  }
  for (unsigned lun = 0; lun < 256; ++lun) {
    auto r = request(p::Command::TestUnitReady, c); r.upiu[2] = uint8_t(lun);
    if (lun != c.selected_lun) reject(r, c);
    auto changed = c; changed.selected_lun = uint8_t(lun);
    r = request(p::Command::TestUnitReady, changed);
    if (lun < 0x80) accept(r, changed); else reject(r, changed);
  }
}

static void testDma()
{
  auto c = context();
  const auto r = request(p::Command::Read10, c);
  const p::Range original[] = {c.dma.allocation, c.dma.utrd, c.dma.request,
                               c.dma.response, c.dma.prdt, c.dma.data};
  for (unsigned i = 0; i < 6; ++i) {
    for (unsigned variant = 0; variant < 6; ++variant) {
      auto bad = c;
      p::Range *parts[] = {&bad.dma.allocation, &bad.dma.utrd, &bad.dma.request,
                          &bad.dma.response, &bad.dma.prdt, &bad.dma.data};
      if (variant == 0) ++parts[i]->address;
      if (variant == 1) --parts[i]->address;
      if (variant == 2) parts[i]->address = UINT64_MAX;
      if (variant == 3) ++parts[i]->bytes;
      if (variant == 4) --parts[i]->bytes;
      if (variant == 5) parts[i]->bytes = UINT64_MAX;
      reject(r, bad);
    }
    for (unsigned j = 0; j < 6; ++j) if (i != j) {
      auto bad = c;
      p::Range *parts[] = {&bad.dma.allocation, &bad.dma.utrd, &bad.dma.request,
                          &bad.dma.response, &bad.dma.prdt, &bad.dma.data};
      parts[i]->address = original[j].address;
      if (i == 0 && j == 1) continue; // UTRD and allocation intentionally share base.
      if (i == 1 && j == 0) continue;
      reject(r, bad);
    }
  }
  for (uint64_t base : {UINT64_C(0), UINT64_C(1), UINT64_MAX & ~UINT64_C(4095)}) {
    auto bad = context(base); reject(request(p::Command::Nop, bad), bad);
  }
  for (uint64_t base : {UINT64_C(0x1000), UINT64_C(0x190000000),
                       UINT64_C(0xfffffffffffdc000)}) {
    const auto high = context(base); accept(request(p::Command::Read10, high), high);
  }
  for (auto cmd : {p::Command::ReadCapacity10, p::Command::Read10}) {
    const auto good = request(cmd, c);
    for (unsigned byte = 8; byte < 16; ++byte) for (unsigned bit = 0; bit < 8; ++bit) {
      auto bad = good; bad.prd[byte] ^= uint8_t(1U << bit); reject(bad, c);
    }
    for (uint64_t address : {c.dma.data.address - 4, c.dma.data.address + 1,
                            c.dma.data.address + c.dma.data.bytes - good.data_bytes + 4,
                            c.dma.data.address + c.dma.data.bytes,
                            c.dma.utrd.address, c.dma.request.address, c.dma.response.address,
                            c.dma.prdt.address, UINT64_MAX - 3}) {
      auto bad = good; prd(bad, address, good.data_bytes); reject(bad, c);
    }
    for (uint64_t address : {c.dma.data.address, c.dma.data.address + 4,
                            c.dma.data.address + c.dma.data.bytes - good.data_bytes}) {
      auto moved = good; prd(moved, address, good.data_bytes);
      assert(accept(moved, c).data_address == address);
    }
  }
}

static void testCapacityAndAllowlist()
{
  const auto c = context(); const auto r = request(p::Command::Read10, c);
  for (unsigned variant = 0; variant < 12; ++variant) {
    auto bad = c;
    if (variant == 0) bad.capacity.measured = false;
    if (variant == 1) ++bad.capacity.lun;
    if (variant == 2) bad.capacity.block_bytes = 512;
    if (variant == 3) bad.capacity.blocks = 0;
    if (variant == 4) bad.capacity.blocks = UINT64_C(0x100000000);
    if (variant == 5) bad.capacity.blocks = UINT64_MAX;
    if (variant == 6) bad.known_block_count = 0;
    if (variant == 7) bad.known_block_count = p::kMaxKnownBlocks + 1;
    if (variant == 8) bad.known_block_count = 0xffffffffU;
    if (variant == 9) ++bad.known_blocks[0].lun;
    if (variant == 10) bad.known_blocks[0].lba = bad.capacity.blocks;
    if (variant == 11) { bad.known_block_count = 2; bad.known_blocks[1] = bad.known_blocks[0]; }
    reject(r, bad);
  }
  for (uint32_t lba : {0U, 6U, 8U, 127U, 128U, 0xffffffffU}) {
    auto bad = r; be32(bad.upiu + 18, lba); reject(bad, c);
  }
  auto maximum = c;
  maximum.capacity.blocks = 0xffffffffU;
  maximum.known_blocks[0].lba = 0xfffffffeU;
  auto last = r; be32(last.upiu + 18, 0xfffffffeU); accept(last, maximum);
  be32(last.upiu + 18, 0xffffffffU); reject(last, maximum);
  auto many = c;
  many.known_block_count = p::kMaxKnownBlocks;
  for (unsigned i = 0; i < p::kMaxKnownBlocks; ++i)
    many.known_blocks[i] = {many.selected_lun, i};
  for (unsigned i = 0; i < p::kMaxKnownBlocks; ++i) {
    auto one = r; be32(one.upiu + 18, i); accept(one, many);
  }
  auto empty = c; empty.capacity = {}; empty.known_block_count = 0;
  for (auto cmd : {p::Command::Nop, p::Command::PowerMode, p::Command::TestUnitReady,
                  p::Command::ReadCapacity10}) accept(request(cmd, empty), empty);

  uint8_t data[8] = {0, 0, 0, 127, 0, 0, 0x10, 0};
  p::Capacity decoded{};
  assert(p::decodeCapacity(data, sizeof(data), c.selected_lun, decoded) == p::Error::None);
  assert(decoded.measured && decoded.blocks == 128 && decoded.block_bytes == 4096 &&
         decoded.lun == c.selected_lun);
  for (uint32_t lastLba : {0U, 127U, 0xfffffffeU}) {
    be32(data, lastLba);
    assert(p::decodeCapacity(data, 8, 0x7f, decoded) == p::Error::None);
    assert(decoded.blocks == uint64_t(lastLba) + 1 && decoded.lun == 0x7f);
  }
  for (unsigned variant = 0; variant < 8; ++variant) {
    be32(data, 127); be32(data + 4, 4096);
    const uint8_t *input = data; size_t len = 8; uint8_t lun = 3;
    if (variant == 0) input = nullptr;
    if (variant == 1) len = 0;
    if (variant == 2) len = 7;
    if (variant == 3) len = 9;
    if (variant == 4) lun = 0x80;
    if (variant == 5) be32(data, 0xffffffffU);
    if (variant == 6) be32(data + 4, 512);
    if (variant == 7) be32(data + 4, 0);
    assert(p::decodeCapacity(input, len, lun, decoded) != p::Error::None);
    assert(!decoded.measured && !decoded.lun && !decoded.blocks && !decoded.block_bytes);
    ++checks;
  }
}

static void response(const p::Accepted &a, uint8_t (&rsp)[512])
{
  std::memset(rsp, 0, sizeof(rsp));
  rsp[2] = a.lun; rsp[3] = a.tag;
  if (a.command == p::Command::Nop) rsp[0] = 0x20;
  else if (a.command == p::Command::PowerMode) {
    rsp[0] = 0x36; rsp[5] = 1; rsp[12] = 3; rsp[13] = 2; rsp[23] = 0x11;
  } else rsp[0] = 0x21;
}
static void rejectResponse(const p::Accepted &a, const p::Context &c,
                           uint32_t ocs, const uint8_t *rsp, size_t len)
{
  p::ResponseResult result{p::ResponseStatus::Completed, p::Error::None, 8, 0x11};
  assert(p::validateResponse(a, c, ocs, rsp, len, result) != p::Error::None);
  assert(result.status == p::ResponseStatus::Rejected && result.error != p::Error::None &&
         result.scsi_status == 0 && result.power_mode == 0);
  ++checks;
}
static void testResponses()
{
  const auto c = context();
  for (auto cmd : commands) {
    const auto a = accept(request(cmd, c), c);
    uint8_t good[512]; response(a, good);
    const bool scsi = good[0] == 0x21;
    const size_t minimum = scsi ? 52 : 32;
    p::ResponseResult out{};
    for (size_t len : {minimum, size_t(128), sizeof(good)}) {
      assert(p::validateResponse(a, c, 0, good, len, out) == p::Error::None);
      assert(out.status == p::ResponseStatus::Completed && out.error == p::Error::None);
      ++checks;
    }
    for (size_t len = 0; len < minimum; ++len) rejectResponse(a, c, 0, good, len);
    rejectResponse(a, c, 0, nullptr, 512);
    rejectResponse(a, c, 0, good, 513);
    rejectResponse(a, c, 0, good, SIZE_MAX);
    for (uint32_t ocs : {1U, 2U, 15U, 16U, 256U, 0xffffffffU})
      rejectResponse(a, c, ocs, good, sizeof(good));
    if (scsi) {
      uint8_t alternate[512]; std::memcpy(alternate, good, sizeof(alternate));
      alternate[11] = 2; // Legal zero-sense-length field in the data segment.
      assert(p::validateResponse(a, c, 0, alternate, sizeof(alternate), out) == p::Error::None);
      assert(out.status == p::ResponseStatus::Completed);
      ++checks;
      for (unsigned status : {8U, 0x28U}) {
        alternate[7] = uint8_t(status);
        assert(p::validateResponse(a, c, 0, alternate, sizeof(alternate), out) == p::Error::None);
        assert(out.status == p::ResponseStatus::Retryable);
        ++checks;
      }
      alternate[7] = 0;
      for (unsigned length : {1U, 3U, 18U, 20U, 255U}) {
        alternate[11] = uint8_t(length); rejectResponse(a, c, 0, alternate, sizeof(alternate));
      }
      alternate[11] = 2;
      for (unsigned byte : {10U, 32U, 33U, 34U, 51U}) {
        alternate[byte] = 1; rejectResponse(a, c, 0, alternate, sizeof(alternate));
        alternate[byte] = 0;
      }
    }
    // All flags, query fields, reserved bytes, lengths, residual, sense and
    // backing-area tail must be canonical. Power value and SCSI status are
    // tested separately because they are typed results, not reserved bytes.
    for (size_t byte = 0; byte < sizeof(good); ++byte) {
      if (cmd == p::Command::PowerMode && byte >= 20 && byte < 24) continue;
      if (scsi && byte == 7) continue;
      uint8_t bad[512]; std::memcpy(bad, good, sizeof(bad)); bad[byte] ^= 1;
      rejectResponse(a, c, 0, bad, sizeof(bad));
    }
    for (unsigned status = 0; status < 256; ++status) {
      uint8_t bad[512]; std::memcpy(bad, good, sizeof(bad)); bad[7] = uint8_t(status);
      if (scsi && (status == 8 || status == 0x28)) {
        assert(p::validateResponse(a, c, 0, bad, sizeof(bad), out) == p::Error::None);
        assert(out.status == p::ResponseStatus::Retryable && out.scsi_status == status);
        bad[15] = 1; rejectResponse(a, c, 0, bad, sizeof(bad));
      } else if (status) rejectResponse(a, c, 0, bad, sizeof(bad));
    }
    if (cmd == p::Command::PowerMode) {
      for (uint32_t value : {0U, 1U, 2U, 0x10U, 0x12U, 0x21U, 0xffffffffU}) {
        uint8_t bad[512]; std::memcpy(bad, good, sizeof(bad)); be32(bad + 20, value);
        assert(p::validateResponse(a, c, 0, bad, sizeof(bad), out) == p::Error::PowerNotReady);
        assert(out.status == p::ResponseStatus::PowerNotReady && out.power_mode == value &&
               out.error == p::Error::PowerNotReady);
        ++checks;
      }
    }
    for (unsigned variant = 0; variant < 9; ++variant) {
      auto bad = a;
      if (variant == 0) bad.valid = false;
      if (variant == 1) bad.command = p::Command::None;
      if (variant == 2) bad.command = static_cast<p::Command>(255);
      if (variant == 3) ++bad.tag;
      if (variant == 4) ++bad.lun;
      if (variant == 5) ++bad.data_bytes;
      if (variant == 6) ++bad.lba;
      if (variant == 7) ++bad.data_address;
      if (variant == 8) bad.data_address = UINT64_MAX;
      rejectResponse(bad, c, 0, good, sizeof(good));
    }
    auto changed = c; ++changed.expected_tag;
    rejectResponse(a, changed, 0, good, sizeof(good));
    changed = c; changed.selected_lun = 0x80;
    rejectResponse(a, changed, 0, good, sizeof(good));
    changed = c; changed.dma.response.bytes = 513;
    rejectResponse(a, changed, 0, good, sizeof(good));
    if (cmd == p::Command::Read10) {
      changed = c; changed.capacity.measured = false;
      rejectResponse(a, changed, 0, good, sizeof(good));
    }
  }
}

// Gate ordering in a fixture only. The production transport must apply the
// same rule itself; this fixture does not establish legacy-path integration.
static void testGateOrdering()
{
  unsigned descriptorWrites = 0, acknowledgements = 0, doorbells = 0;
  auto c = context();
  const auto run = [&](const p::Request &r) {
    p::Accepted a{};
    if (p::validateRequest(r, c, a) != p::Error::None) return false;
    ++descriptorWrites; ++acknowledgements; ++doorbells;
    return true;
  };
  auto r = request(p::Command::TestUnitReady, c); r.upiu[16] = 0x1b;
  assert(!run(r));
  r = request(p::Command::Read10, c); r.direction = p::Direction::ToDevice;
  assert(!run(r));
  r = request(p::Command::Read10, c); le32(r.prd, uint32_t(c.dma.request.address));
  assert(!run(r));
  assert(descriptorWrites == 0 && acknowledgements == 0 && doorbells == 0);
  assert(run(request(p::Command::Read10, c)));
  assert(descriptorWrites == 1 && acknowledgements == 1 && doorbells == 1);
}

int main()
{
  testRequestPackets(); testDma(); testCapacityAndAllowlist(); testResponses(); testGateOrdering();
  std::printf("ReadCommandPolicy: %u packet, DMA, capacity and response checks passed\n", checks);
}
