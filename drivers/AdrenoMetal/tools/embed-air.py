#!/usr/bin/env python3
"""Assemble a hand-written AIR kernel (LLVM IR text) and write it as a C byte array header for the plugin.

  embed-air.py shaders/scale_bgra.ll ScaleKernelAir.h kScaleKernelAir

Needs llvm-as (LLVM 21 or newer; Homebrew's llvm). The header is checked in, so the plugin build needs neither.
"""
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

source, header, name = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
llvm_as = next((p for p in ['/opt/homebrew/opt/llvm/bin/llvm-as', shutil.which('llvm-as') or ''] if p and Path(p).exists()), None)
if not llvm_as:
    sys.exit('llvm-as (LLVM 21 or newer) is required')
with tempfile.TemporaryDirectory() as work:
    air = Path(work) / 'kernel.air'
    subprocess.run([llvm_as, '-o', str(air), str(source)], check=True)
    data = air.read_bytes()
rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
header.write_text(
    '// SPDX-License-Identifier: MIT\n'
    f'// Generated by tools/embed-air.py from {source.as_posix()} ({len(data)} bytes of AIR bitcode). Do not edit.\n'
    '#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n'
    f'static const uint8_t {name}[] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'
    f'static const size_t {name}Length = sizeof {name};\n')
print(f'{header}: {len(data)} bytes')
