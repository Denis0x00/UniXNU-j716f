static void seed_ensure_dir(proc_t p, uint64_t scratch, const char *path, uid_t uid, gid_t gid, int mode) {
 int32_t result = 0;
 if (copyout(path, scratch, strlen(path) + 1) != 0) return;
 struct mkdir_args md = { .path = scratch, .mode = mode };
 int err = mkdir(p, &md, &result);
 if (err != 0 && err != EEXIST) return;
 struct open_args op = { .path = scratch, .flags = O_RDONLY | O_DIRECTORY | O_NOFOLLOW, .mode = 0 };
 if (open(p, &op, &result) == 0) {
  int fd = result;
  struct fchown_args own = { .fd = fd, .uid = uid, .gid = gid };
  (void)fchown(p, &own, &result);
  struct fchmod_args chm = { .fd = fd, .mode = mode };
  (void)fchmod(p, &chm, &result);
  struct close_args cl = { .fd = fd };
  (void)sys_close(p, &cl, &result);
 }
}

static int seed_write_plist(proc_t p, uint64_t scratch, const char *path,
                            const unsigned char *data, size_t len, uid_t uid, gid_t gid) {
 int32_t result = 0;
 if (copyout(path, scratch, strlen(path) + 1) != 0) return -1;
 struct open_args op = { .path = scratch, .flags = O_WRONLY | O_CREAT | O_TRUNC | O_NOFOLLOW, .mode = 0644 };
 int err = open(p, &op, &result);
 if (err != 0) return 0;
 int fd = result;
 int ok = 1;
 for (size_t sent = 0; sent < len; ) {
  size_t piece = (len - sent) < 0x1f0 ? (len - sent) : 0x1f0;
  if (copyout(data + sent, scratch + 0x200, piece) != 0) { ok = 0; break; }
  struct write_args wr = { .fd = fd, .cbuf = scratch + 0x200, .nbyte = piece };
  user_ssize_t written = 0;
  if (write(p, &wr, &written) != 0 || written != (user_ssize_t)piece) { ok = 0; break; }
  sent += piece;
 }
 if (ok) {
  struct fchown_args own = { .fd = fd, .uid = uid, .gid = gid };
  (void)fchown(p, &own, &result);
  struct fchmod_args chm = { .fd = fd, .mode = 0644 };
  (void)fchmod(p, &chm, &result);
  struct fsync_args syn = { .fd = fd };
  (void)fsync(p, &syn, &result);
 }
 struct close_args cl = { .fd = fd };
 (void)sys_close(p, &cl, &result);
 return ok;
}

